import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import { Sampler, apply, createSampler, handleSnapshotRequest, handleKillRequest, killProcess } from '../lib/index.js'
const sleep = ms => new Promise(r => setTimeout(r, ms))
const jsonRequest = body => new Request('http://localhost/api/sysmon.kill', { method: 'POST', body: JSON.stringify(body) })
// Deterministic CPU-delta, PID reuse, network reset and bounded history tests.
const synthetic = new Sampler()
const record = (ts, start = '123456789012345678', time = ts / 1000, rx = ts * 100) => ({ v: 1, monoMs: ts, ts, procs: [{ pid: 100, start, time, rss: 1024, thr: 1, cmd: 'fixture' }], net: [{ id: 'n', name: 'Ethernet', rx, tx: rx }], disks: [], errors: [] })
synthetic.accept(record(1000))
assert.equal(synthetic.procs[0].cpu, null)
synthetic.accept(record(2000))
assert.ok(synthetic.procs[0].cpu > 0 && synthetic.procs[0].cpu <= 100)
assert.equal(synthetic.net.rxBps, 100000)
synthetic.accept(record(3000, '223456789012345678', 0, 0))
assert.equal(synthetic.procs[0].cpu, null)
assert.equal(synthetic.net.rxBps, null)
for (let i = 4; i < 110; i++) synthetic.accept(record(i * 1000))
for (const values of Object.values(synthetic.hist)) assert.equal(values.length, 90)
synthetic.stop()
assert.equal(synthetic.previous, null)
assert.deepEqual(synthetic.procs, [])
for (const values of Object.values(synthetic.hist)) assert.equal(values.length, 0, 'disposal releases retained samples')
const diskSampler = new Sampler()
const diskRecord = (ts, readBytes, writeBytes) => ({ ...record(ts), disks: [{ name: 'PhysicalDrive0', readBytes, writeBytes }] })
diskSampler.accept(diskRecord(1000, 1024, 2048))
assert.equal(diskSampler.disk.readBps, null, 'disk throughput needs two counter samples')
diskSampler.accept(diskRecord(3000, 3072, 6144))
assert.equal(diskSampler.disk.readBps, 1024)
assert.equal(diskSampler.disk.writeBps, 2048)
diskSampler.accept(diskRecord(5000, 0, 0))
assert.equal(diskSampler.disk.readBps, null, 'reset disk counters require a fresh baseline')
diskSampler.stop()
for (const pid of [0, 1, 4, process.pid, process.ppid, -1, 1.5, '1234', null]) assert.equal((await killProcess(pid)).status, 400)
assert.equal((await killProcess(100, 'TERM', '123456789012345678')).status, 400)
assert.equal((await killProcess(100, 'KILL')).status, 400)
for (const body of [null, [], { pid: 1 }]) assert.equal((await handleKillRequest(jsonRequest(body))).status, 400)
assert.equal((await handleKillRequest(new Request('http://localhost/api/sysmon.kill'))).status, 405)
assert.equal((await handleKillRequest(new Request('http://localhost/api/sysmon.kill', { method: 'POST', body: 'bad' }))).status, 400)
const response = await handleSnapshotRequest({ async getSnapshot() { throw Error('probe failed') } }, new Request('http://localhost/api/sysmon.snapshot'))
assert.equal(response.status, 503)
const routes = new Map(), disposers = []
apply({ effect(fn) { disposers.push(fn()) }, connection: { fetch: { register(route) { routes.set(route.path, route); return () => routes.delete(route.path) } } } })
assert.equal(routes.size, 2)
for (const dispose of disposers.reverse()) dispose()
assert.equal(routes.size, 0)
console.log('PASS: math, PID reuse, counter reset, history, input validation, routes, disposal')
if (process.platform !== 'win32') {
  await assert.rejects(createSampler().getSnapshot(), /Windows/)
  console.log('SKIP: real Windows integration (requires Windows 10/11)')
  process.exit(0)
}
const sampler = createSampler()
// Keep the standalone runner alive while the unref'ed production worker samples.
const keepAlive = setTimeout(() => {}, 25000)
const child = spawn(process.execPath, ['-e', 'setInterval(()=>{},1000)'], { windowsHide: true, stdio: 'ignore' })
await once(child, 'spawn')
try {
  let snapshot = await sampler.getSnapshot()
  assert.ok(snapshot.procs.length > 0)
  assert.ok(snapshot.mem.total > 0)
  assert.ok(snapshot.host.topology.logicalProcessors > 0)
  assert.ok(snapshot.host.topology.physicalCores > 0)
  assert.ok(Array.isArray(snapshot.gpu.devices))
  await sleep(2600)
  snapshot = await sampler.getSnapshot()
  assert.ok(Number.isFinite(snapshot.cpu.usage))
  assert.ok(snapshot.hist.cpu.length >= 2)
  const victim = snapshot.procs.find(p => p.pid === child.pid)
  assert.ok(victim?.start, 'test child identity should be readable')
  const exit = once(child, 'exit')
  assert.equal((await killProcess(child.pid, 'KILL', '123456789012345678')).body.ok, false)
  assert.equal(child.exitCode, null, 'wrong creation time must not terminate child')
  const ended = await handleKillRequest(jsonRequest({ pid: child.pid, signal: 'KILL', start: victim.start }))
  assert.equal(ended.status, 200, JSON.stringify(await ended.clone().json()))
  await exit
  console.log(JSON.stringify({ host: snapshot.host.osName, processes: snapshot.procs.length, cpu: snapshot.cpu.usage, diskDevices: snapshot.disk.devices.length, warnings: snapshot.warnings }))
  sampler.lastRequestAt = Date.now() - 7000
  await sleep(1200)
  assert.equal(sampler.worker, null, 'idle collector should stop')
  console.log('PASS: real Windows sampling, termination of owned test child, idle shutdown')
} finally { child.kill(); sampler.stop(); clearTimeout(keepAlive) }
