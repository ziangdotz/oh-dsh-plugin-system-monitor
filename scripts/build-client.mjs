import { readFile, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const normalize = text => text.replaceAll('\r\n', '\n')
const read = async name => normalize(await readFile(new URL(`../src/client/${name}`, import.meta.url), 'utf8'))
const template = await read('module.js')
let bundle = '// Generated by scripts/build-client.mjs; edit src/client instead.\n' + template
for (const match of template.matchAll(/\/\* @include ([\w.-]+) \*\//g)) bundle = bundle.replace(match[0], await read(match[1]))
const output = new URL('../lib/client.js', import.meta.url)
if (process.argv.includes('--check')) assert.equal(normalize(await readFile(output, 'utf8')), bundle, 'Client bundle is outdated; run npm run build:client')
else await writeFile(output, bundle)
